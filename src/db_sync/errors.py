"""Исключения модуля."""


class SyncError(Exception):
    """Базовое исключение модуля."""


class ValidationError(SyncError):
    """Некорректные входные данные (имя таблицы, адрес БД, направление)."""


class ConnectionFailed(SyncError):
    """Не удалось подключиться к базе или нет нужного драйвера."""


class SafetyError(SyncError):
    """Действие заблокировано защитой (нет подтверждения записи на сервер)."""
